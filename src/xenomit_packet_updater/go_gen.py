"""Generate xenomit-server live protocol catalog from modules.json."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from .catalog import Module

# Ops that are flat scalars; everything else becomes opaque.
_FLAT_OPS = {
    "i8",
    "u8",
    "i16",
    "u16",
    "i32",
    "u32",
    "f32",
    "f64",
    "bool",
    "utf",
    "i8_rot",
    "u8_rot",
    "i16_rot",
    "u16_rot",
    "i32_rot",
    "u32_rot",
    "skip_i16",
    "lit_i16",
}


def _op_yaml(op: dict[str, Any]) -> str:
    name = op.get("op", "unknown")
    field = op.get("name") or "_"
    if name in _FLAT_OPS:
        parts = [f"name: {field}", f"type: {name}"]
        if "dir" in op:
            parts.append(f"dir: {op['dir']}")
        if "bits" in op:
            parts.append(f"bits: {op['bits']}")
        if "width" in op:
            parts.append(f"width: {op['width']}")
        return "{" + ", ".join(parts) + "}"
    return "{" + f"name: {field}, type: opaque, op: {name}" + "}"


def _direction(mod: Module) -> str:
    has_r = bool(mod.read_ops)
    has_w = bool(mod.write_ops)
    if has_r and has_w:
        return "both"
    if has_w:
        return "in"  # client write → server inbound
    if has_r:
        return "out"
    return "both"


def generate_live_yaml(
    catalog: dict[str, Module],
    class_names: dict[str, str],
) -> str:
    lines = [
        "# Generated by xenomit-packet-updater. DO NOT EDIT.",
        "# Live Bigpoint catalog (u24 framing). Independent of spec/commands.yaml (v10).",
        "commands:",
    ]
    for key in sorted(class_names.values(), key=str.lower):
        mod = catalog.get(key)
        if mod is None or mod.module_id is None:
            continue
        lines.append(f"  - name: {mod.name}")
        lines.append(f"    id: {mod.module_id}")
        lines.append(f"    direction: {_direction(mod)}")
        # Prefer write_ops for client→server shape; fall back to read
        ops = mod.write_ops or mod.read_ops
        lines.append("    fields:")
        if not ops:
            lines.append("      []")
            continue
        for op in ops:
            if not isinstance(op, dict):
                continue
            lines.append(f"      - {_op_yaml(op)}")
    lines.append("")
    return "\n".join(lines)


def _sorted_mods(
    catalog: dict[str, Module], class_names: dict[str, str]
) -> list[Module]:
    mods: list[Module] = []
    for key in sorted(class_names.values(), key=str.lower):
        mod = catalog.get(key)
        if mod is not None and mod.module_id is not None:
            mods.append(mod)
    return mods


def generate_live_go(
    catalog: dict[str, Module],
    class_names: dict[str, str],
) -> str:
    mods = _sorted_mods(catalog, class_names)
    width = max((len(m.name) + 2 for m in mods), default=8)  # Name + "ID"
    lines = [
        "// Code generated by xenomit-packet-updater. DO NOT EDIT.",
        "",
        "// Package live is the current Bigpoint DarkOrbit module-id catalog",
        "// extracted from the live client. Framing for this catalog is u24",
        "// (see xenomit-packet-client). The v10 package remains the private-",
        "// server emulator catalog with u16 framing.",
        "package live",
        "",
        "const (",
    ]
    for mod in mods:
        name = f"{mod.name}ID"
        lines.append(f"\t{name:<{width}} int16 = {mod.module_id}")
    lines.append(")")
    lines.append("")
    lines.append("// ByName maps ActionScript class name → module id.")
    lines.append("var ByName = map[string]int16{")
    for mod in mods:
        lines.append(f'\t"{mod.name}": {mod.name}ID,')
    lines.append("}")
    lines.append("")
    lines.append("// ByID maps module id → ActionScript class name.")
    lines.append("var ByID = map[int16]string{")
    for mod in mods:
        lines.append(f'\t{mod.name}ID: "{mod.name}",')
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def write_live_catalog(
    server: Path,
    catalog: dict[str, Module],
    class_names: dict[str, str],
) -> list[str]:
    written: list[str] = []
    yaml_path = server / "spec" / "live-commands.yaml"
    go_dir = server / "pkg" / "protocol" / "live"
    go_path = go_dir / "catalog.go"
    yaml_path.parent.mkdir(parents=True, exist_ok=True)
    go_dir.mkdir(parents=True, exist_ok=True)
    yaml_path.write_text(
        generate_live_yaml(catalog, class_names), encoding="utf-8"
    )
    go_path.write_text(
        generate_live_go(catalog, class_names), encoding="utf-8"
    )
    written.extend([str(yaml_path), str(go_path)])
    return written
